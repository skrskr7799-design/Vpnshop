"""Generate the MZT V5 SVG path data from the original handoff geometry."""

import json
import math

C, R0, STEP, W = 500, 95, 53, 17        # centre, inner radius, ring pitch, wall thickness (matches style.css)
HALF = W / 2
r_of = lambda k: R0 + STEP * k            # wall rings 0..7

# --- design table: arcs per ring (start, end in degrees, clockwise) and radial walls per corridor ---
ARCS = {
    0: [(25, 155), (170, 335)],           # core ring, wider opening at 3 o'clock
    1: [(7.5, 55), (70, 160), (175, 245), (260, 352.5)],
    2: [(7.5, 98), (113, 185), (200, 275), (290, 352.5)],
    3: [(7.5, 62), (77, 150), (165, 226), (241, 302), (317, 352.5)],
    4: [(7.5, 92), (107, 173), (188, 266), (281, 352.5)],
    5: [(7.5, 43), (58, 142), (157, 235), (250, 317), (332, 352.5)],
    6: [(7.5, 87), (102, 179), (194, 268), (283, 352.5)],
    7: [(7.5, 171), (186, 352.5)],
}
RADIALS = {0: [155], 1: [55, 260], 2: [98, 200], 3: [62, 165, 302], 4: [92, 188, 281], 5: [43, 142, 250], 6: [87, 194]}

pt = lambda r, a: (C + r * math.cos(math.radians(a)), C + r * math.sin(math.radians(a)))
num = lambda v: f"{v:.2f}".rstrip("0").rstrip(".")
xy = lambda p: f"{num(p[0])} {num(p[1])}"

def arc(r, a0, a1):
    return f"M{xy(pt(r, a0))}A{num(r)} {num(r)} 0 {1 if a1 - a0 > 180 else 0} 1 {xy(pt(r, a1))}"

def has_radial(k, a):                      # radial wall touching ring k at angle a (either side)
    return any(abs(x - a) < .01 for c in (k - 1, k) for x in RADIALS.get(c, []))

def covers(k, a):
    return any(a0 - .01 <= a <= a1 + .01 for a0, a1 in ARCS[k])

for c, angles in RADIALS.items():          # sanity: every radial must land on rings at both ends
    for a in angles:
        assert covers(c, a) and covers(c + 1, a), f"radial {a} in corridor {c} hangs in the air"

rings = []
for k, arcs in ARCS.items():
    r = r_of(k)
    extension = math.degrees(HALF / r)
    rings.append("".join(
        arc(r, a0 - extension * has_radial(k, a0), a1 + extension * has_radial(k, a1))
        for a0, a1 in arcs
    ))

spokes = "".join(
    f"M{xy(pt(r_of(c), a))}L{xy(pt(r_of(c + 1), a))}"
    for c, angles in RADIALS.items() for a in angles
)

# Include wall caps when checking the straight approach at three o'clock.
for k, arcs in ARCS.items():
    assert all(min(a0, 360 - a1) > math.degrees(HALF / r_of(k)) for a0, a1 in arcs)
assert all(0 < a < 360 for angles in RADIALS.values() for a in angles)

print("// Generated by packages/ui/scripts/generate-maze.py from the MZT V5 design.")
print("export const mazeRings = "+json.dumps(rings, indent=2)+" as const;")
print("export const mazeSpokes = "+json.dumps(spokes)+";")
